# Calculadora de Comissões e Bônus Mensal
# ============================================================

print("=== SISTEMA DE CÁLCULO DE COMISSÕES E BÔNUS ===\n")

META_BONUS = 20000.00
VALOR_BONUS = 300.00

qtd_vendedores = int(input("Quantidade de vendedores: "))

total_comissoes = 0.0
total_bonus = 0.0
total_a_pagar = 0.0
qtd_meta = 0

for i in range(1, qtd_vendedores + 1):
    print(f"\n--- Vendedor {i} de {qtd_vendedores} ---")
    nome = input("Nome do vendedor: ")

    # Validação: recusa valores negativos e pede novamente
    total_vendido = float(input("Total vendido no mês (R$): "))
    while total_vendido < 0:
        print("Valor inválido: o total vendido não pode ser negativo. Digite novamente.")
        total_vendido = float(input("Total vendido no mês (R$): "))

    # Mínimos de vendas para comissão
    if total_vendido <= 10000.00:
        percentual = 2
    elif total_vendido <= 30000.00:
        percentual = 4
    else:
        percentual = 6

    comissao = total_vendido * percentual / 100

    # Bônus por meta
    if total_vendido >= META_BONUS:
        bonus = VALOR_BONUS
        qtd_meta += 1
    else:
        bonus = 0.0

    valor_receber = comissao + bonus

    total_comissoes += comissao
    total_bonus += bonus
    total_a_pagar += valor_receber

    print(f"Vendedor: {nome}")
    print(f"Total vendido: R$ {total_vendido:.2f}")
    print(f"Percentual aplicado: {percentual}%")
    print(f"Comissão: R$ {comissao:.2f}")
    print(f"Bônus: R$ {bonus:.2f}")
    print(f"Valor a receber: R$ {valor_receber:.2f}")

print("\n===== RESUMO FINAL =====")
print(f"Vendedores processados: {qtd_vendedores}")
print(f"Total de comissões: R$ {total_comissoes:.2f}")
print(f"Total de bônus: R$ {total_bonus:.2f}")
print(f"Total geral a pagar: R$ {total_a_pagar:.2f}")
print(f"Vendedores que bateram a meta: {qtd_meta}")